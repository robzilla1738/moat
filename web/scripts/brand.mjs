// Generate every brand artefact from brand/*.svg and brand/design-tokens.json:
//
//   * web/src/tokens.css                         CSS variables for light and dark
//   * web/public/favicon.svg, icons/*.png         favicon, apple-touch, PWA (any + maskable)
//   * macos/Moat/App/Assets.xcassets              AppIcon (every macOS size), MenuBarIcon (template), colour sets
//   * brand/png/*.png                             the mark and icon as PNGs for docs
//
//   CHROMIUM_PATH=/usr/bin/chromium node web/scripts/brand.mjs      everything
//   node web/scripts/brand.mjs --tokens                              tokens.css and colour sets only (no browser)
//
// Rasterising goes through Chromium (the same engine the screenshot checks use), so there is no extra native tool.
import { mkdir, readFile, writeFile, copyFile, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const brand = join(root, "brand");
const tokens = JSON.parse(await readFile(join(brand, "design-tokens.json"), "utf8"));
const svg = async (name) => readFile(join(brand, name), "utf8");

// ---------------------------------------------------------------------------------------------------------- tokens.css
{
  const block = (sel, scheme, c) => `${sel} {\n  color-scheme: ${scheme};\n${Object.entries(c).map(([k, v]) => `  --${k}: ${v};`).join("\n")}\n}\n`;
  const css =
    `/* Generated by web/scripts/brand.mjs from brand/design-tokens.json. Do not edit by hand. */\n` +
    block(":root,\n[data-theme=\"light\"]", "light", tokens.color.light) +
    block("[data-theme=\"dark\"]", "dark", tokens.color.dark) +
    `:root {\n${Object.entries(tokens.space).filter(([k]) => k !== "note").map(([k, v]) => `  --s-${k}: ${v}px;`).join("\n")}\n${Object.entries(tokens.type).filter(([k]) => k !== "note").map(([k, v]) => `  --t-${k}: ${v}px;`).join("\n")}\n${Object.entries(tokens.weight).map(([k, v]) => `  --w-${k}: ${v};`).join("\n")}\n  --font-sans: ${tokens.font.sans};\n  --font-mono: ${tokens.font.mono};\n  --radius-card: ${tokens.radius.card}px;\n  --radius-inner: ${tokens.radius.inner}px;\n  --radius-control: ${tokens.radius.control}px;\n  --hit: ${tokens["hit-target"]}px;\n}\n`;
  await writeFile(join(root, "web/src/tokens.css"), css);
}

const xc = join(root, "macos/Moat/App/Assets.xcassets");
const xcColors = join(xc, "Colors");
await mkdir(xc, { recursive: true });
await writeFile(join(xc, "Contents.json"), JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n");
await rm(xcColors, { recursive: true, force: true });
// Semantic colour sets: one per token, with a dark appearance.
const comp = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return { "color-space": "srgb", components: { red: `0x${((n >> 16) & 255).toString(16).padStart(2, "0").toUpperCase()}`, green: `0x${((n >> 8) & 255).toString(16).padStart(2, "0").toUpperCase()}`, blue: `0x${(n & 255).toString(16).padStart(2, "0").toUpperCase()}`, alpha: "1.000" } };
};
const camel = (k) => "Moat" + k.split("-").map((s) => s[0].toUpperCase() + s.slice(1)).join("");
for (const key of Object.keys(tokens.color.light)) {
  const dir = join(xcColors, `${camel(key)}.colorset`);
  await mkdir(dir, { recursive: true });
  await writeFile(
    join(dir, "Contents.json"),
    JSON.stringify({ colors: [{ idiom: "universal", color: comp(tokens.color.light[key]) }, { idiom: "universal", appearances: [{ appearance: "luminosity", value: "dark" }], color: comp(tokens.color.dark[key]) }], info: { author: "xcode", version: 1 } }, null, 2) + "\n",
  );
}
await writeFile(join(xcColors, "Contents.json"), JSON.stringify({ info: { author: "xcode", version: 1 }, properties: { "provides-namespace": false } }, null, 2) + "\n");
// AccentColor follows the brand accent in both appearances.
await mkdir(join(xc, "AccentColor.colorset"), { recursive: true });
await writeFile(
  join(xc, "AccentColor.colorset", "Contents.json"),
  JSON.stringify({ colors: [{ idiom: "universal", color: comp(tokens.color.light["accent-strong"]) }, { idiom: "universal", appearances: [{ appearance: "luminosity", value: "dark" }], color: comp(tokens.color.dark["accent-strong"]) }], info: { author: "xcode", version: 1 } }, null, 2) + "\n",
);

if (process.argv.includes("--tokens")) {
  console.log("tokens written");
  process.exit(0);
}

// ------------------------------------------------------------------------------------------------------------- rasters
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
async function png(svgText, size, out, { tint } = {}) {
  const page = await browser.newPage({ viewport: { width: Math.max(size, 256), height: Math.max(size, 256) }, deviceScaleFactor: 1 }); // tiny viewports hang Chromium screenshots
  const body = svgText.replace("<svg", `<svg width="${size}" height="${size}" style="display:block${tint ? `;color:${tint}` : ""}"`);
  await page.setContent(`<html><body style="margin:0;background:transparent">${body}</body></html>`);
  await mkdir(dirname(out), { recursive: true });
  await page.screenshot({ path: out, omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
  await page.close();
}

const icon = await svg("moat-icon.svg");
const maskable = await svg("moat-icon-maskable.svg");
const macIcon = await svg("moat-app-icon-macos.svg");
const mark = await svg("moat-mark.svg");

// web
const pub = join(root, "web/public");
await copyFile(join(brand, "moat-icon.svg"), join(pub, "favicon.svg"));
await png(icon, 32, join(pub, "icons/favicon-32.png"));
await png(maskable, 180, join(pub, "icons/apple-touch-icon.png")); // iOS applies its own corner mask
await png(icon, 192, join(pub, "icons/icon-192.png"));
await png(icon, 512, join(pub, "icons/icon-512.png"));
await png(maskable, 512, join(pub, "icons/icon-maskable-512.png"));

// macOS AppIcon: every size the asset catalog asks for
const appicon = join(xc, "AppIcon.appiconset");
const images = [];
for (const pt of [16, 32, 128, 256, 512]) {
  for (const scale of [1, 2]) {
    const px = pt * scale;
    const file = `icon_${pt}x${pt}${scale === 2 ? "@2x" : ""}.png`;
    await png(macIcon, px, join(appicon, file));
    images.push({ filename: file, idiom: "mac", scale: `${scale}x`, size: `${pt}x${pt}` });
  }
}
await writeFile(join(appicon, "Contents.json"), JSON.stringify({ images, info: { author: "xcode", version: 1 } }, null, 2) + "\n");

// Menu bar: a template image (black + alpha); macOS tints it for the menu bar appearance.
const menubar = join(xc, "MenuBarIcon.imageset");
await png(mark, 18, join(menubar, "menubar.png"), { tint: "#000" });
await png(mark, 36, join(menubar, "menubar@2x.png"), { tint: "#000" });
await writeFile(
  join(menubar, "Contents.json"),
  JSON.stringify({ images: [{ filename: "menubar.png", idiom: "mac", scale: "1x" }, { filename: "menubar@2x.png", idiom: "mac", scale: "2x" }], info: { author: "xcode", version: 1 }, properties: { "template-rendering-intent": "template", "preserves-vector-representation": false } }, null, 2) + "\n",
);

// docs PNGs
const lightMark = await svg("moat-mark-light.svg");
const darkMark = await svg("moat-mark-dark.svg");
await png(lightMark, 256, join(brand, "png/moat-mark-light-256.png"));
await png(darkMark, 256, join(brand, "png/moat-mark-dark-256.png"));
await png(macIcon, 1024, join(brand, "png/moat-app-icon-1024.png"));
await png(icon, 512, join(brand, "png/moat-icon-512.png"));

await browser.close();
console.log("brand artefacts written");
